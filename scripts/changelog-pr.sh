#!/bin/bash
# Opens the pull request that adds a release to CHANGELOG.md and sets it to
# merge itself once CI is green.
#
#   scripts/changelog-pr.sh <version> [previous-tag]
#
# For the release workflow, after the release is published. Every failure from
# the push on warns instead of failing: the release is already out, and a red
# run would misrepresent that. Needs GH_TOKEN and DEFAULT_BRANCH; HAS_PAT=true
# when GH_TOKEN is the RELEASE_PAT. By hand: scripts/changelog.sh prepend, then
# open the PR yourself.
set -euo pipefail
cd "$(dirname "$0")/.."

VERSION="${1:-}"
PREVIOUS="${2:-}"
[[ -n "${VERSION}" ]] || { echo "usage: changelog-pr.sh <version> [previous-tag]" >&2; exit 2; }
[[ "${GITHUB_ACTIONS:-}" == "true" ]] || {
    echo "error: for the release workflow only. It force-pushes a branch and can store a token in the remote URL." >&2
    exit 2
}
: "${GH_TOKEN:?GH_TOKEN is required}"
: "${DEFAULT_BRANCH:?DEFAULT_BRANCH is required}"
: "${RUNNER_TEMP:?RUNNER_TEMP is required}"
HAS_PAT="${HAS_PAT:-false}"

BRANCH="docs/changelog-v${VERSION}"
# A worktree of its own: checking the branch out here would replace this
# script while bash still reads it.
WORKTREE="${RUNNER_TEMP}/changelog"
git fetch origin "${DEFAULT_BRANCH}"
git worktree add -B "${BRANCH}" "${WORKTREE}" "origin/${DEFAULT_BRANCH}"
cd "${WORKTREE}"
scripts/changelog.sh prepend "${VERSION}" "${PREVIOUS}" "v${VERSION}"

if git diff --quiet -- CHANGELOG.md; then
    echo "CHANGELOG.md already up to date."
    exit 0
fi
git add CHANGELOG.md
# No [skip ci] here: the required checks have to report before the PR can
# merge. The squash commit gets it through --subject below.
git commit -m "docs: changelog for v${VERSION}"

# GH_TOKEN authenticates gh, never git, so the push needs the credential in
# the remote URL. actions/checkout stores GITHUB_TOKEN as an extra header that
# reaches this worktree too and wins over the URL. The push clears it, or a
# re-run's push would start no CI on the open PR.
push=(git push)
if [[ "${HAS_PAT}" == "true" ]]; then
    git remote set-url origin "https://x-access-token:${GH_TOKEN}@github.com/${GITHUB_REPOSITORY}.git"
    push=(git -c "http.https://github.com/.extraheader=" push)
fi
# -f rather than --force-with-lease: a re-run of the same version owns this
# branch outright, and there's no lease for a ref never fetched.
"${push[@]}" -f origin "${BRANCH}" || {
    echo "::warning::Could not push ${BRANCH}. Run 'scripts/changelog.sh prepend ${VERSION}' locally and open the PR yourself."
    exit 0
}

if [[ -z "$(gh pr list --head "${BRANCH}" --base "${DEFAULT_BRANCH}" --state open --json number --jq '.[].number')" ]]; then
    gh pr create --base "${DEFAULT_BRANCH}" --head "${BRANCH}" \
        --title "docs: changelog for v${VERSION}" \
        --body "Generated by the release workflow for [v${VERSION}](${GITHUB_SERVER_URL}/${GITHUB_REPOSITORY}/releases/tag/v${VERSION}). Merges once CI is green." || {
        echo "::warning::Could not open the changelog PR for v${VERSION}; the branch ${BRANCH} is pushed, so open it by hand."
        exit 0
    }
fi

# Dispatching ci.yml on the branch is no substitute for the PAT (measured):
# its checks never reach the head commit's status-check rollup, which is what
# the merge gate reads. Closing and reopening the PR does work.
if [[ "${HAS_PAT}" != "true" ]]; then
    echo "::warning::No RELEASE_PAT secret, so CI won't start for the changelog PR on its own and it can't merge. Close and reopen it once; it merges itself when the checks go green."
fi

gh pr merge "${BRANCH}" --auto --squash --delete-branch \
    --subject "docs: changelog for v${VERSION} [skip ci]" || \
    echo "::warning::Could not enable auto-merge; merge the changelog PR by hand once CI is green."
